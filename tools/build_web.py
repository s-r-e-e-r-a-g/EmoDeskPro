#!/usr/bin/env python3
"""Pack web/index.html into EmoDesk/web_ui.h (gzipped, PROGMEM).

Run after editing the dashboard (PlatformIO does it automatically):
    python3 tools/build_web.py
"""
import gzip, hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "web", "index.html")
OUT = os.path.join(ROOT, "EmoDesk", "web_ui.h")


def squeeze(html: str) -> str:
    # Light, safe minification: drop comments and leading indentation.
    html = re.sub(r"<!--(?!\[).*?-->", "", html, flags=re.S)
    html = re.sub(r"/\*.*?\*/", "", html, flags=re.S)
    lines = [l.strip() for l in html.splitlines()]
    return "\n".join(l for l in lines if l and not l.startswith("// "))


def main():
    with open(SRC, encoding="utf-8") as f:
        html = squeeze(f.read())
    data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)
    etag = '"' + hashlib.sha1(data).hexdigest()[:12] + '"'
    rows = []
    for i in range(0, len(data), 20):
        rows.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 20]))
    body = (
        "// Generated by tools/build_web.py from web/index.html - do not edit\n"
        "#pragma once\n#include <Arduino.h>\n"
        f"#define DASH_GZ_LEN {len(data)}\n"
        f"#define DASH_ETAG \"{etag.replace(chr(34), chr(92) + chr(34))}\"\n"
        "static const uint8_t DASH_GZ[] PROGMEM = {\n" + ",\n".join(rows) + "\n};\n"
    )
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old != body:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(body)
    print(f"web_ui.h: {len(html)} bytes -> {len(data)} gzipped")


if __name__ == "__main__":
    sys.exit(main())
